"""
LRC + масс-зависимость: честная проверка на согласованность с реальными
экспериментальными границами на модели типа CSL.

ЧТО ДОБАВЛЕНО ПО СРАВНЕНИЮ С ОРИГИНАЛЬНЫМ drgoogerencia.py
------------------------------------------------------------
1. Масс-зависимость. В оригинале Gamma0 - это одна и та же константа для
   электрона и для футбольного мяча при одинаковом Δx. Это противоречит
   базовому наблюдаемому факту квантово-классического перехода: чем массивнее
   (точнее - чем больше число некогерентно складывающихся составляющих N)
   объект, тем быстрее он теряет когерентность при том же Δx.

   Во всех настоящих collapse-моделях (GRW, CSL) это реализовано через
   амплификацию скорости коллапса при переходе от одной частицы к телу из
   N частиц:

       Gamma0_N = Gamma0_1 * N^alpha

   где Gamma0_1 - скорость для ОДНОЙ частицы (референсная масса m0 = 1 а.е.м.),
   alpha = 2 для когерентного (CSL-подобного) усиления, если тело
   пространственно локализовано в объёме меньше корреляционной длины rC.
   Это НЕ доказанный факт о LRC - это единственный физически разумный способ
   добавить в LRC то свойство, без которого модель либо (а) уже противоречит
   интерферометрии лёгких частиц, либо (б) непроверяема в принципе.

2. Отображение LRC-параметров (Gamma0, L0) в CSL-подобные (lambda, r_C),
   чтобы можно было сравнить с ОПУБЛИКОВАННЫМИ границами:

       lambda  <->  Gamma0_1   (скорость для одной частицы, м0 = 1 а.е.м.)
       r_C     <->  L0

   Это соответствие приблизительное (формы функций похожи по структуре -
   насыщающаяся экспонента от (Δx/масштаб)^2 - но не идентичны). Оно годится
   для оценки порядка величины, не для точного количественного вывода.

3. Ориентировочные (не оцифрованные попиксельно, а взятые как порядковые
   реперные точки из текстов статей) границы:
     - GRW: lambda ~ 1e-16 1/с при r_C = 1e-7 м
     - Adler: lambda ~ 1e-8 .. 1e-9 1/с при r_C = 1e-7 м (нижние оценки,
       во многом уже исключены)
     - Матер-wave интерферометрия (Toros/Bassi и др.): lambda(rC=1e-7 м)
       порядка нескольких x1e2..1e3 1/c как верхняя граница (до улучшений)
     - Холодные атомы (Bilardello et al. 1605.01891): lambda/r_C^2 < 5e6 м^-2 с^-1
     - Нанокантилеверы (Vinante et al.): улучшение границы интерферометрии
       на ~2 порядка, исключают Adler почти полностью при rC >= 3e-7 м

   ВАЖНО: это ориентиры для порядка величины, не точные оцифрованные кривые.
   Для публикационного уровня точности нужно доставать реальные данные/таблицы
   из статей (например, через WebPlotDigitizer по Fig. 7 из 1605.01891 или
   Fig. 3 из 1510.05791).
"""

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

C = 299792458.0  # м/с


# ============================================================
# МОДЕЛЬ С МАСС-ЗАВИСИМОСТЬЮ
# ============================================================
class LRCModelMassScaled:
    def __init__(self, gamma0_single=1e6, L0=300.0, gamma_env=0.0, alpha=2.0):
        """
        gamma0_single : скорость декогеренции ОДНОЙ частицы (референс m0=1 а.е.м.)
                        при Δx >> L0 (насыщение)
        L0            : характерный масштаб длины (аналог r_C в CSL)
        alpha         : показатель усиления с числом частиц N
                        (alpha=2 - когерентная CSL-подобная амплификация,
                         физически обоснованный выбор по умолчанию)
        """
        self.gamma0_single = gamma0_single
        self.L0 = L0
        self.gamma_env = gamma_env
        self.alpha = alpha

    def gamma0_for_N(self, N):
        return self.gamma0_single * (N ** self.alpha)

    def gamma_lrc(self, dx, N):
        z = np.abs(dx) / self.L0
        extra = self.gamma0_for_N(N) * (1.0 - np.exp(-z * z))
        return self.gamma_env + extra

    def visibility(self, dx, t, N):
        return np.exp(-self.gamma_lrc(dx, N) * t)


# ============================================================
# ПРОВЕРКА 1: НЕ ПРОТИВОРЕЧИТ ЛИ МОДЕЛЬ УЖЕ СУЩЕСТВУЮЩЕЙ
# ИНТЕРФЕРОМЕТРИИ ЛЁГКИХ ЧАСТИЦ (нейтроны/электроны/фотоны)?
# ============================================================
def check_light_particle_interferometry(model, dx_meters, t_seconds, N=1,
                                          min_observed_visibility=0.5):
    """
    Нейтронная/электронная интерферометрия рутинно показывает высокую
    видимость интерференции (V > 0.5, часто > 0.9) при разносе путей
    порядка сантиметров и времени пролёта порядка микросекунд-миллисекунд.
    Если предсказанная LRC-видимость на этих масштабах уже сильно меньше
    наблюдаемой - параметры модели исключены немедленно, без всякой CSL-
    математики.
    """
    v_pred = model.visibility(dx_meters, t_seconds, N)
    excluded = v_pred < min_observed_visibility
    return v_pred, excluded


# ============================================================
# ПРОВЕРКА 2: СОПОСТАВЛЕНИЕ С CSL-ГРАНИЦАМИ (порядок величины)
# ============================================================
def lrc_to_csl_equivalent(model):
    """Прямое отображение параметров (без изменения чисел)."""
    return {"lambda_equiv": model.gamma0_single, "rC_equiv": model.L0}


# Ориентировочные реперные точки из литературы (lambda [1/с], rC [м]).
# Источники см. в шапке файла. ЭТО ПОРЯДОК ВЕЛИЧИНЫ, НЕ ТОЧНЫЕ ДАННЫЕ.
REFERENCE_POINTS = {
    "GRW (теоретическая)":            (1e-16, 1e-7),
    "Adler (нижняя оценка)":          (1e-8,  1e-7),
    "Матер-wave интерферометрия (верх. граница, ~2016)": (1e2, 1e-7),
    "Нанокантилеверы (верх. граница, лучше на ~2 порядка)": (1.0, 1e-7),
}


def plot_comparison(model, N_values, out_path):
    fig, ax = plt.subplots(figsize=(8, 6))

    # Ваша модель, показанная как ТОЧКА (lambda_equiv, rC_equiv) для
    # референсной частицы (N=1), плюс - куда она уезжает при амплификации
    # для составных объектов разной массы (N=840 - C70, N~1e10 - вирус, и т.д.)
    csl = lrc_to_csl_equivalent(model)
    ax.scatter([csl["rC_equiv"]], [csl["lambda_equiv"]],
               color="red", s=80, zorder=5,
               label=f"LRC, N=1 (ваши параметры)")

    for N, label in N_values:
        lam_N = model.gamma0_for_N(N)
        ax.scatter([csl["rC_equiv"]], [lam_N], marker="^", s=60,
                   label=f"LRC амплифицир. N={N:.0e} ({label})")

    for name, (lam, rc) in REFERENCE_POINTS.items():
        ax.scatter([rc], [lam], marker="x", s=90)
        ax.annotate(name, (rc, lam), fontsize=8, xytext=(5, 5),
                    textcoords="offset points")

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("r_C эквивалент (м)  [<-> L0]")
    ax.set_ylabel("lambda эквивалент (1/с)  [<-> Gamma0]")
    ax.set_title("LRC-параметры (N=1 и с амплификацией) на фоне\n"
                  "ориентировочных литературных границ CSL (порядок величины)")
    ax.legend(fontsize=7, loc="best")
    ax.grid(alpha=0.3, which="both")
    fig.tight_layout()
    fig.savefig(out_path, dpi=140)
    print(f"[OK] график сохранён: {out_path}")


